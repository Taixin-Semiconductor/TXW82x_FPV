int32 magic_voice_write(magic_voice_struct *magic_voice_s, int16 *data, uint32 *nsamples)
{
    int ret = RET_ERR;
    struct auchange_req req;
    if(magic_voice_s) {
        if(magic_voice_s->type != g_magic_voice_type) {
            uint32 pitch = 100;
            switch(g_magic_voice_type) {
                case original_voice: pitch = 100; break; 
                case alien_voice: pitch = 130; break; 
                case robot_voice: pitch = 90; break;
                case hight_voice: pitch = 150; break;
                case deep_voice: pitch = 70; break; 
                case etourdi_voice: pitch = 120; break; 
                default: break;
            }
            auchange_ioctl(magic_voice_s->auchange_dev, magic_voice_s->auchange_chan, AUCHANGE_IOCTL_SET_PITCH, pitch);
            magic_voice_s->type = g_magic_voice_type;
        }

        uint8 delaySamples = 0;
        int32 temp32 = 0;
        uint32 in_nsamples = *nsamples;
        os_memcpy(magic_voice_s->delay_buf + in_nsamples, data, in_nsamples * sizeof(int16));
        if(magic_voice_s->type == alien_voice) {
            for(uint32 i=0; i<in_nsamples; i++) {
                if(magic_voice_s->table_index < 500)
                    delaySamples = delaySamples_table[magic_voice_s->table_index];
                else
                    delaySamples = delaySamples_table[999-magic_voice_s->table_index];
                data[i] = ((int32)(magic_voice_s->delay_buf[i + in_nsamples - delaySamples])+magic_voice_s->delay_buf[i + in_nsamples])>>1;
                magic_voice_s->table_index = (magic_voice_s->table_index + 1) % 1000;
            }
            os_memcpy(magic_voice_s->delay_buf, magic_voice_s->delay_buf + in_nsamples, in_nsamples * sizeof(int16));   
        }
        else if(magic_voice_s->type == robot_voice) {
            int16 delay_data = 0;
            int16 back_data = 0;
            delaySamples = 80;
            for(uint32 i=0; i<in_nsamples; i++) {
                delay_data = magic_voice_s->delay_buf[(i + in_nsamples - delaySamples)];
                back_data = delay_data;
                temp32 = ((int32)(magic_voice_s->delay_buf[in_nsamples + i] >> 1) + delay_data) * 8 / 10;
                data[i] = SETW32TOW16(temp32);
                temp32 = (magic_voice_s->delay_buf[in_nsamples+i] >> 1) + (back_data << 2) / 5;
                magic_voice_s->delay_buf[in_nsamples + i] = SETW32TOW16(temp32);
            }
            os_memcpy(magic_voice_s->delay_buf,magic_voice_s->delay_buf + in_nsamples, in_nsamples * sizeof(int16));        
        }

        req.chan = magic_voice_s->auchange_chan;
        req.data = data;
        req.nsamples = *nsamples;
        ret = auchange_write(magic_voice_s->auchange_dev, &req);
        *nsamples = req.nsamples;
    }
    return ret;
}

int32 magic_voice_read(magic_voice_struct *magic_voice_s, int16 *data, uint32 *nsamples)
{
    int ret = RET_ERR;
    struct auchange_req req;
    if(magic_voice_s) {
        req.chan = magic_voice_s->auchange_chan;
        req.data = data;
        req.nsamples = *nsamples;
        ret = auchange_read(magic_voice_s->auchange_dev, &req);
        *nsamples = req.nsamples;
    }
    return ret;
}

int32 magic_voice_read_available(magic_voice_struct *magic_voice_s)
{
    uint32 nsamples = 0;
    if(magic_voice_s) {
        auchange_ioctl(magic_voice_s->auchange_dev, magic_voice_s->auchange_chan, AUCHANGE_IOCTL_READ_AVAILABLE, (uint32)(&nsamples));
    }
    return nsamples;
}

int32 magic_voice_set_type(uint8 type)
{
    int ret = RET_ERR;
    g_magic_voice_type = type;
    return ret;    
}

int32 magic_voice_deinit(magic_voice_struct *magic_voice_s)
{
    int ret = RET_ERR;
    if(magic_voice_s) {
        if(magic_voice_s->auchange_chan) {
            auchange_close(magic_voice_s->auchange_dev, magic_voice_s->auchange_chan);
        }
        if(magic_voice_s->delay_buf) {
            os_free_psram(magic_voice_s->delay_buf);
        }
        os_free(magic_voice_s);
        ret = RET_OK;
    }
    return ret;    
}

magic_voice_struct *magic_voice_init(uint32_t samplerate, uint32_t size)
{
    if((samplerate != 8000) || (size != 160)) {
        os_printf("magic voice param abormal\n");
        return NULL;
    }
    magic_voice_struct *magic_voice_s = (magic_voice_struct*)os_zalloc_psram(sizeof(magic_voice_struct));
    if(magic_voice_s == NULL) {
        return NULL;
    }
    magic_voice_s->auchange_dev = (struct auchange_device*)dev_get(HG_AUDIO_CHANGER_DEVID);
    if(magic_voice_s->auchange_dev == NULL) {
        goto magic_voice_init_fail;
    }
    magic_voice_s->auchange_chan = auchange_open(magic_voice_s->auchange_dev, samplerate, 1, size);
    if(magic_voice_s->auchange_chan == NULL) {
        goto magic_voice_init_fail;   
    }
    magic_voice_s->delay_buf = (int16*)os_malloc_psram(size * sizeof(int16) + 320);
    if(magic_voice_s->delay_buf == NULL) {
        goto magic_voice_init_fail;        
    }
    magic_voice_s->frame_size = size;
    magic_voice_s->type = original_voice;
	return magic_voice_s;
magic_voice_init_fail:
    if(magic_voice_s->auchange_chan) {
        auchange_close(magic_voice_s->auchange_dev, magic_voice_s->auchange_chan);
    }
    if(magic_voice_s->delay_buf) {
        os_free_psram(magic_voice_s->delay_buf);
    }
    os_free(magic_voice_s);
    return NULL;
}