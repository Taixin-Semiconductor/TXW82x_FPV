static int8_t get_font_index(char ch)
{
    int8_t num = ch - 0x30;

    if (ch == '/')
    {
        num = 10;
    }
    else if (ch == ':')
    {
        num = 11;
    }
    else if (ch == '-')
    {
        num = 12;
    }
    else if (num < 0 || num > 10)
    {
        num = -1;
    }

    return num;
}

static void draw_char_build(struct watermark_msi_s *watermark, const char *str, uint32_t second)
{
    int char_num = 0;
    int char_idx;

    if (!watermark)
    {
        return;
    }

    memset(watermark->sec_run_num, 0, sizeof(watermark->sec_run_num));
    watermark->sec_valid = 1;
    watermark->sec_sec   = second;
    watermark->sec_width = 0;

    if (!str)
    {
        return;
    }

    while (str[char_num] && char_num < WATERMARK_TIME_CHAR_MAX)
    {
        char_num++;
    }
    watermark->sec_width = char_num * FONT_W;

    for (char_idx = 0; char_idx < char_num; char_idx++)
    {
        int8_t num = get_font_index(str[char_idx]);
        if (num >= 0)
        {
            const uint8_t *font = font_data[num];
            for (int row = 0; row < FONT_H; row++)
            {
                uint16_t bits = ((uint16_t)font[row * 2] << 8) | font[row * 2 + 1];
                int      col  = 0;
                while (col < FONT_W)
                {
                    while (col < FONT_W && !(bits & (0x8000 >> col)))
                    {
                        col++;
                    }

                    if (col < FONT_W)
                    {
                        int      start = col;
                        uint16_t abs_start;
                        uint16_t len;
                        uint16_t run_idx;

                        while (col < FONT_W && (bits & (0x8000 >> col)))
                        {
                            col++;
                        }

                        abs_start = (uint16_t)(char_idx * FONT_W + start);
                        len       = (uint16_t)(col - start);
                        run_idx   = watermark->sec_run_num[row];

                        if (run_idx < WATERMARK_RUN_MAX_PER_ROW)
                        {
                            watermark->sec_run[row][run_idx].start_x = abs_start;
                            watermark->sec_run[row][run_idx].len     = len;
                            watermark->sec_run_num[row]++;
                        }
                    }
                }
            }
        }
    }
}

static char draw_char(struct watermark_msi_s *watermark, char *yuv_buf, const char *str, uint32_t second, int w, int h, int x, int y, int color)
{
    if (!watermark || !yuv_buf || !str)
    {
        return 0;
    }

    if (!watermark->sec_valid || watermark->sec_sec != second)
    {
        draw_char_build(watermark, str, second);
    }

    int dst_x = 0, dst_y = 0, len = 0;

    for (int row = 0; row < FONT_H; row++)
    {
        dst_y = y + row;

        if (dst_y >= 0 && dst_y < h && watermark->sec_run_num[row])
        {
            for (uint16_t run_idx = 0; run_idx < watermark->sec_run_num[row]; run_idx++)
            {
                dst_x = x + watermark->sec_run[row][run_idx].start_x;
                len   = watermark->sec_run[row][run_idx].len;

                if (dst_x < 0)
                {
                    len += dst_x;
                    dst_x = 0;
                }
                if (dst_x + len > w)
                {
                    len = w - dst_x;
                }

                if (len > 0)
                {
                    memset(yuv_buf + dst_y * w + dst_x, color, len);
                }
            }
        }
    }

    return 0;
}

static int32_t watermark_work(struct os_work *work)
{
    struct yuv_arg_s       *arg;
    struct watermark_msi_s *watermark = (struct watermark_msi_s *) work;
    struct framebuff       *fb;
    uint32_t                send_count;

    fb = msi_get_fb(watermark->msi, 0);

    // 检查是否需要发送到下一级
    if (fb && !watermark->output_en)
    {
        send_count = msi_output_fb(watermark->msi, NULL);
        if (!send_count)
        {
            msi_delete_fb(NULL, fb);
            fb = NULL;
        }
        else
        {
            watermark->output_en = 1;
        }
    }

    if (fb)
    {
        char       path[64];
        uint32_t   second;
        struct tm *time_info;
        struct timeval ptimeval;
        gettimeofday(&ptimeval, NULL);
        time_t time_val = (time_t)ptimeval.tv_sec;
        time_info = gmtime(&time_val);
        uint32_t year	=	time_info->tm_year + 1900;
        uint32_t mon 	=	time_info->tm_mon + 1;
        uint32_t day 	=	time_info->tm_mday;
        uint32_t hour 	= 	time_info->tm_hour;
        uint32_t min 	= 	time_info->tm_min;
        uint32_t sec 	= 	time_info->tm_sec;
        int flush_x = 0, flush_y = 0, flush_w = 0, flush_h = 0;

        os_sprintf(path, "%04d/%02d/%02d %02d:%02d:%02d", year,mon,day,hour, min, sec);
        second = (uint32_t)time_val;
        arg = (struct yuv_arg_s *) fb->priv;
        // 增加水印后,发出去
        draw_char(watermark, (char*)fb->data, path, second, arg->out_w, arg->out_h, watermark->x, watermark->y, watermark->color);
        if (watermark->sec_width)
        {
            flush_x = watermark->x;
            flush_y = watermark->y;
            flush_w = watermark->sec_width;
            flush_h = FONT_H;

            if (flush_x < 0)
            {
                flush_w += flush_x;
                flush_x = 0;
            }
            if (flush_y < 0)
            {
                flush_h += flush_y;
                flush_y = 0;
            }
            if (flush_x + flush_w > arg->out_w)
            {
                flush_w = arg->out_w - flush_x;
            }
            if (flush_y + flush_h > arg->out_h)
            {
                flush_h = arg->out_h - flush_y;
            }
            if (flush_w > 0 && flush_h > 0)
            {
                uint32_t start = (uint32_t)(fb->data + flush_y * arg->out_w + flush_x);
                uint32_t end   = start + (flush_h - 1) * arg->out_w + flush_w;
                start &= ~0x1F;
                end = (end + 0x1F) & (~0x1F);
                sys_dcache_clean_invalid_range((uint32_t *)(start), end - start);
            }
        }
        send_count = msi_output_fb(watermark->msi, fb);
        if (!send_count)
        {
            watermark->output_en = 0;
        }
    }
    return 0;
}

static int32_t watermark_msi_action(struct msi *msi, uint32_t cmd_id, uint32_t param1, uint32_t param2)
{
    int32_t                 ret       = RET_OK;
    struct watermark_msi_s *watermark = (struct watermark_msi_s *) msi->priv;
    switch (cmd_id)
    {
        case MSI_CMD_POST_DESTROY:
        {
            os_work_cancle2(&watermark->work, 1);
            STREAM_LIBC_FREE(watermark);
        }
        break;

        case MSI_CMD_PRE_DESTROY:
        {
            os_work_cancle2(&watermark->work, 1);
        }
        break;

        case MSI_CMD_TRANS_FB:
        {
            struct framebuff *fb = (struct framebuff *) param1;
            if (fb->mtype != F_YUV)
            {
                ret = RET_ERR;
            }
            // 如果需要过滤,并且过滤类型不匹配就不增加水印
            if (watermark->filter && watermark->filter != fb->stype)
            {
                ret = RET_ERR;
            }
            if(ret == RET_OK && !watermark->watermark_en)
            {
                fb_get(fb);
                msi_output_fb(watermark->msi, fb);
                ret = RET_ERR;
            }
        }
        break;
        case MSI_CMD_TRANS_FB_END:
        {
            os_run_work(&watermark->work);
        }
        break;
        case MSI_CMD_WATERMARK:
        {
            uint32_t cmd_self = param1;
            uint32_t arg      = param2;
            switch(cmd_self)
            {
                case MSI_WATERMARK_SET_X_Y:
                {
                    watermark->x = (int)((arg >> 16) & 0xFFFF);
                    watermark->y = (int)(arg & 0xFFFF);
                }
                break;
                case MSI_WATERMARK_SET_COLOR:
                {
                    watermark->color = (int)arg;
                }
                break;
                case MSI_WATERMARK_SET_ENABLE:
                {
                    watermark->watermark_en = (uint8_t)arg;
                }
                break;
            }
        }
        break;
        default:
        {
        }
        break;
    }
    return ret;
}
// 中转(路由)msi,不需要接收,仅仅发送就可以了
struct msi *yuv_time_watermark(const char *name, uint8_t filter)
{
    // 设置1个接收,只是为了可以output_fb给到这个msi
    uint8_t     isnew;
    struct msi *msi = msi_new(name, 8, &isnew);
    if (isnew)
    {
        struct watermark_msi_s *watermark = (struct watermark_msi_s *) STREAM_LIBC_ZALLOC(sizeof(struct watermark_msi_s));
        ASSERT(watermark);
        watermark->msi          = msi;
        watermark->filter       = filter;
        watermark->x            = WATERMARK_X;
        watermark->y            = WATERMARK_Y;
        watermark->color        = WATERMARK_COLOR;
        watermark->watermark_en = 1;
        msi->priv               = (void *) watermark;
        msi->action             = watermark_msi_action;
        OS_WORK_INIT(&watermark->work, watermark_work, 0);
        os_run_work_delay(&watermark->work, 1);
        msi->enable = 1;
    }
    return msi;
}
