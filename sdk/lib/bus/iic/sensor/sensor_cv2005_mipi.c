void CV2005_ae_adjust(struct isp_exposure_opt *p_cfg)
{
    uint8 index         = 0;
    uint32 shutter0     = 0;
    uint32 cv2005_gain  = 0;
    uint8  *addr        = (uint8 *)p_cfg->data.addr;


    for (int i = 0; i < (CV2005_MaxGainIndex); i++){
        if(p_cfg->analog_gain <=CV2005_sensorGainMapping[i][1]){
            cv2005_gain = CV2005_sensorGainMapping[i][0];
            break;
        }
    }
	shutter0 = 1200 - p_cfg->exposure_line;
	
	/*GAIN*/
    addr[index++] = 0x31;
    addr[index++] = 0x14;
    addr[index++] = (cv2005_gain);
	
	/*SHUTTER0*/
    addr[index++] = 0x30;
    addr[index++] = 0x48;
    addr[index++] = (uint8)(shutter0 & 0xff);
    addr[index++] = 0x30;
    addr[index++] = 0x49;
    addr[index++] = (uint8)(shutter0 >> 8);
    addr[index++] = 0x30;
    addr[index++] = 0x4A;
    addr[index++] = (uint8)((shutter0 >> 16) & 0x0F);
	
	
    p_cfg->data.size = index;
    p_cfg->cmd_len   = 2+1;
}

