void ov9734_ae_adjust(struct isp_exposure_opt *p_cfg)
{
    uint8 index         = 0;
    uint8  *addr        = (uint8 *)p_cfg->data.addr;
	
    addr[index++] = 0x35;
    addr[index++] = 0x00;
    addr[index++] = ((p_cfg->exposure_line<<4)>>16) & 0x0f;//p_cfg->exposure_line << ;

    addr[index++] = 0x35;
    addr[index++] = 0x01;
    addr[index++] = ((p_cfg->exposure_line<<4)>>8) & 0xff;//p_cfg->exposure_line;
    addr[index++] = 0x35;
    addr[index++] = 0x02;
    addr[index++] = (p_cfg->exposure_line<<4) & 0xf0;
    addr[index++] = 0x35;
    addr[index++] = 0x0b;
    addr[index++] = (p_cfg->analog_gain) >> 4;
    p_cfg->data.size = index;
    p_cfg->cmd_len   = 2+1;
}

void ov9734_img_opt(struct isp_sensor_opt *p_opt)
{
    uint8  *addr = (uint8 *)p_opt->data.addr;
    uint8  index = 0;
    uint8  reg_val = 0x10;  
    addr[index++] = 0x38;
    addr[index++] = 0x20;
    
    if(p_opt->mirror_en){
        reg_val |= (1<<3);  // Bit[3]: Mirror
    }
    if(p_opt->reverse_en){
        reg_val |= (1<<2);  // Bit[2]: Flip
        reg_val |= (1<<4);  // Bit[4]: BLC_flip
    }
    addr[index++] = reg_val;

    p_opt->data.size = index;
    p_opt->cmd_len   = 2+1;
}

void ov9734_fps_opt(struct isp_sensor_opt *p_opt)
{
    uint8  *addr        = (uint8 *)p_opt->data.addr;
    uint8  index        = 0;
    addr[index++]       = 0x38;
    addr[index++]       = 0x0e;
    addr[index++]       = p_opt->curr_length >> 8;
    addr[index++]       = 0x38;
    addr[index++]       = 0x0f;
    addr[index++]       = p_opt->curr_length & 0xff;
    p_opt->data.size    = index;
    p_opt->cmd_len      = 2+1;
}

